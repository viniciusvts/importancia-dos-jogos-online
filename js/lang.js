let currentLanguage = localStorage.getItem("language") || "en-US";

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "pt-BR" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (translations[key] && translations[key][language]) {
      element.textContent = translations[key][language];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    const key = element.dataset.i18nAlt;
    if (translations[key] && translations[key][language]) {
      element.setAttribute("alt", translations[key][language]);
    }
  });

  localStorage.setItem("language", language);

  // Trigger language change events for dynamic game texts if needed
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { language } }));
}

function initLanguage() {
  const savedLang = localStorage.getItem("language");
  const initialLang = savedLang || "en-US";
  setLanguage(initialLang);

  const toggleBtn = document.getElementById("language-toggle");
  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      const nextLang = currentLanguage === "en-US" ? "pt-BR" : "en-US";
      setLanguage(nextLang);
    });
  }
}

// Export functions for global accessibility
window.setLanguage = setLanguage;
window.getCurrentLanguage = () => currentLanguage;
window.initLanguage = initLanguage;
